import markUrl from '@/assets/fluxora-mark.svg'
import smallMarkUrl from '@/assets/fluxora-mark-small.svg'
import monoUrl from '@/assets/fluxora-mark-mono.svg'
import lightUrl from '@/assets/fluxora-mark-light.svg'
import { cn } from '@/lib/utils'

/** Below this size the fine taper closes up, so a bolder cut is used. */
const SMALL_MARK_MAX = 40

type MarkVariant = 'metallic' | 'light' | 'mono'

const SOURCES: Record<MarkVariant, string> = {
  metallic: markUrl,
  light: lightUrl,
  mono: monoUrl,
}

/**
 * The Fluxora vortex mark.
 *
 * `metallic` is the default and is the reference treatment (champagne metal on
 * obsidian). `light` is for light surfaces. `mono` paints with `currentColor`
 * through a CSS mask, so it inherits text colour anywhere it is used.
 *
 * Geometry is generated by scripts/brand/generate-assets.js — never inline the
 * mark by hand.
 */
export function FluxoraMark({
  size = 24,
  tile,
  variant = 'metallic',
  className,
}: {
  size?: number
  /** Kept for API compatibility; the tile treatment is baked into icon assets. */
  tile?: boolean
  variant?: MarkVariant
  className?: string
}) {
  void tile

  if (variant === 'mono') {
    return (
      <span
        role="img"
        aria-label="Fluxora"
        className={cn('inline-block shrink-0 bg-current', className)}
        style={{
          width: size,
          height: size,
          WebkitMaskImage: `url(${monoUrl})`,
          maskImage: `url(${monoUrl})`,
          WebkitMaskSize: 'contain',
          maskSize: 'contain',
          WebkitMaskRepeat: 'no-repeat',
          maskRepeat: 'no-repeat',
          WebkitMaskPosition: 'center',
          maskPosition: 'center',
        }}
      />
    )
  }

  const source = variant === 'metallic' && size <= SMALL_MARK_MAX ? smallMarkUrl : SOURCES[variant]

  return (
    <img
      src={source}
      width={size}
      height={size}
      className={cn('shrink-0', className)}
      alt="Fluxora"
      draggable={false}
    />
  )
}

export function FluxoraLockup({
  size = 18,
  className,
  textClassName,
  subtitle,
}: {
  size?: number
  className?: string
  textClassName?: string
  subtitle?: string
}) {
  return (
    <div className={cn('flex items-center gap-2.5', className)}>
      <FluxoraMark size={size} className="shrink-0" />
      <div className="min-w-0">
        <div className={cn('fx-wordmark select-none text-[13px] leading-none', textClassName)}>FLUXORA</div>
        {subtitle ? (
          <div className="mt-1 truncate text-[9px] uppercase tracking-[0.18em] text-muted-foreground/70">
            {subtitle}
          </div>
        ) : null}
      </div>
    </div>
  )
}
